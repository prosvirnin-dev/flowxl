"""Russian Excel function names mapped to the English names stored in xlsx.

Excel always stores formulas in en-US. A Russian UI shows СУММ, ЕСЛИ, ВПР.
This table is the reverse of that display mapping. Keys are folded: upper
case, Cyrillic yo replaced with ye, so СЧЁТ and СЧЕТ hit the same entry.
"""

from __future__ import annotations

from typing import Final

__all__ = ['BARE_CONSTANTS', 'RU_TO_EN', 'fold_name']


def fold_name(name: str) -> str:
    """Fold a function name for dictionary lookup.

    Args:
        name: Identifier as written in a formula.

    Returns:
        Uppercase name with yo replaced by ye.
    """
    return name.upper().replace('Ё', 'Е')


